"""Generates user_overrides.lua, the only Lua this app writes. hyprland.lua loads it last, so values here
override the tracked config without anyone editing tracked files. Everything is optional: with no
overrides the file does nothing."""

from __future__ import annotations

import os
import re
from pathlib import Path
from typing import Any

BANNER = "-- Generated by hypr-settings from user_settings.local.toml. Do not edit by hand: changes are overwritten.\n"
_STARTUP_BLOCK = re.compile(r"--\s*STARTUP-APPS-BEGIN.*?--\s*STARTUP-APPS-END", re.S)
_STARTUP_ROW = re.compile(r'\{\s*id\s*=\s*"([^"]+)"\s*,\s*label\s*=\s*"([^"]+)"\s*,\s*cmd\s*=\s*"([^"]+)"\s*\}')


def lua_value(value: Any) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return repr(value)
    if isinstance(value, str):
        escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r")
        return f'"{escaped}"'
    raise TypeError(f"cannot write {type(value).__name__} to Lua")


def _nest(pairs: list[tuple[tuple, Any]]) -> dict:
    tree: dict = {}
    for path, value in pairs:
        node = tree
        for part in path[:-1]:
            node = node.setdefault(part, {})
        node[path[-1]] = value
    return tree


def _render_table(tree: dict, indent: int) -> str:
    pad, inner = " " * indent, " " * (indent + 4)
    rows = []
    for key in sorted(tree):
        value = tree[key]
        rows.append(f"{inner}{key} = {_render_table(value, indent + 4) if isinstance(value, dict) else lua_value(value)},")
    return "{\n" + "\n".join(rows) + f"\n{pad}}}"


def render(config: list[tuple[tuple, Any]], apps: dict[str, str], startup_disabled: list[str]) -> str:
    out = [BANNER, "local M = {}\n"]
    out.append("M.apps = " + (_render_table({k: v for k, v in sorted(apps.items())}, 0) if apps else "{}") + "\n")
    out.append("M.startup_disabled = " + (
        "{\n" + "\n".join(f"    [{lua_value(name)}] = true," for name in sorted(startup_disabled)) + "\n}" if startup_disabled else "{}") + "\n")
    if config:
        out.append("function M.apply()\n    hl.config(" + _render_table(_nest(config), 4) + ")\nend\n")
    else:
        out.append("function M.apply() end\n")
    out.append("return M\n")
    return "\n".join(out)


def write(path: Path | str, text: str) -> None:
    path = Path(path)
    tmp = path.with_name(path.name + f".{os.getpid()}.tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


def startup_apps(autostart_lua: Path | str) -> list[dict]:
    """Optional startup apps declared between STARTUP-APPS markers in autostart.lua: [{id, label, cmd}]."""
    try:
        text = Path(autostart_lua).read_text(encoding="utf-8")
    except OSError:
        return []
    block = _STARTUP_BLOCK.search(text)
    if not block:
        return []
    return [{"id": i, "label": label, "cmd": cmd} for i, label, cmd in _STARTUP_ROW.findall(block.group(0))]
