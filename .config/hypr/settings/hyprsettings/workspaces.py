"""Workspace rules in workspaces.lua (machine-local, git-ignored): which screen each workspace opens on, which one a
screen starts on, a name, whether it always shows in the bar, and an app to open when it is empty.

Rules for other workspaces, and options this page does not show, are kept exactly as they were."""

from __future__ import annotations

import os
import re
import subprocess
from pathlib import Path

from .overrides import lua_value

BANNER = "-- Generated by hypr-settings (Workspaces page). Do not edit by hand: changes are overwritten.\n"
COUNT = 10  # Super+1 .. Super+0
FIELDS = ("monitor", "default", "persistent", "default_name", "on_created_empty")
_RULE = re.compile(r"hl\.workspace_rule\(\s*\{(.*?)\}\s*\)", re.S)
_PAIR = re.compile(r'(\w+)\s*=\s*("(?:[^"\\]|\\.)*"|true|false|-?\d+(?:\.\d+)?)')


def _value(text: str):
    if text in ("true", "false"):
        return text == "true"
    if text.startswith('"'):
        return re.sub(r"\\(.)", lambda m: {"n": "\n", "r": "\r"}.get(m[1], m[1]), text[1:-1])
    return float(text) if "." in text else int(text)


def read(path: Path | str) -> dict[str, dict]:
    """workspace -> its options, in file order. {} when the file is missing."""
    try:
        text = Path(path).read_text(encoding="utf-8")
    except OSError:
        return {}
    rules: dict[str, dict] = {}
    for block in _RULE.findall(text):
        opts = {k: _value(v) for k, v in _PAIR.findall(block)}
        ws = str(opts.pop("workspace", "")).strip()
        if ws:
            rules.setdefault(ws, {}).update(opts)
    return rules


def rows(rules: dict[str, dict]) -> list[dict]:
    """Workspaces 1-10 for the page: {id, monitor, default, persistent, name, app}. Empty strings mean not set."""
    out = []
    for n in range(1, COUNT + 1):
        r = rules.get(str(n), {})
        out.append({"id": n, "monitor": str(r.get("monitor", "")), "default": bool(r.get("default", False)),
                    "persistent": bool(r.get("persistent", False)), "name": str(r.get("default_name", "")),
                    "app": str(r.get("on_created_empty", ""))})
    return out


def merge(rules: dict[str, dict], page: list[dict]) -> dict[str, dict]:
    """The page's choices laid over the file's rules; anything the page does not manage is left alone."""
    out = {ws: dict(opts) for ws, opts in rules.items()}
    for row in page:
        opts = {k: v for k, v in out.get(str(row["id"]), {}).items() if k not in FIELDS}
        if row["monitor"]:
            opts["monitor"] = row["monitor"]
        if row["default"] and row["monitor"]:
            opts["default"] = True
        if row["persistent"]:
            opts["persistent"] = True
        if row["name"].strip():
            opts["default_name"] = row["name"].strip()
        if row["app"].strip():
            opts["on_created_empty"] = row["app"].strip()
        if opts:
            out[str(row["id"])] = opts
        else:
            out.pop(str(row["id"]), None)
    return out


def render(rules: dict[str, dict]) -> str:
    def order(ws):
        return (0, int(ws)) if ws.isdigit() else (1, ws)
    parts = [BANNER]
    for ws in sorted(rules, key=order):
        body = [f"workspace = {lua_value(ws)}"] + [f"{k} = {lua_value(v)}" for k, v in rules[ws].items()]
        parts.append("hl.workspace_rule({ " + ", ".join(body) + " })\n")
    return "".join(parts)


def write(path: Path | str, rules: dict[str, dict]) -> None:
    path = Path(path)
    old = path.read_text(encoding="utf-8", errors="replace") if path.exists() else ""
    if old.strip() and BANNER.split(".")[0] not in old[:200]:
        path.with_name(path.name + ".bak").write_text(old, encoding="utf-8")  # someone else's file: keep a copy once
    tmp = path.with_name(path.name + f".{os.getpid()}.tmp")
    tmp.write_text(render(rules), encoding="utf-8")
    os.replace(tmp, path)


def _hyprctl(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["hyprctl", *args], capture_output=True, text=True, timeout=10)


def apply(rules: dict[str, dict]) -> tuple[bool, str]:
    """Reloads Hyprland so the rules take effect, then moves workspaces that are already open onto their screen
    (rules alone only affect workspaces made from now on). Your focus stays where it is."""
    try:
        r = _hyprctl("reload")
        if r.returncode != 0:
            return False, (r.stdout or r.stderr).strip()[:300] or "Hyprland did not reload."
        errors = _hyprctl("configerrors").stdout.strip()
        if errors and errors != "[]":
            return False, "Hyprland reported a problem with the config:\n" + errors[:400]
        import json
        open_ws = {str(w["id"]): w["monitor"] for w in json.loads(_hyprctl("workspaces", "-j").stdout or "[]")}
        screens = {m["name"] for m in json.loads(_hyprctl("monitors", "-j").stdout or "[]")}
    except (OSError, ValueError, subprocess.SubprocessError) as e:
        return False, f"Could not talk to Hyprland: {e}"
    moved = []
    for ws, opts in rules.items():
        want = opts.get("monitor")
        if ws in open_ws and want in screens and open_ws[ws] != want:
            _hyprctl("dispatch", f"hl.dsp.workspace.move({{ workspace = {lua_value(ws)}, monitor = {lua_value(want)} }})")
            moved.append(ws)
    return True, (f"Applied. Moved workspace {', '.join(moved)} to its screen." if moved else "Applied.")
