"""Screens: read them from Hyprland, change them live, and remember the layout in monitors.lua.

Replaces nwg-displays. Changes are applied with `hyprctl eval` (so they show immediately) and written to
monitors.lua, which hyprland.lua loads on every start. Nothing here needs the TUI, so it can be tested alone."""

from __future__ import annotations

import json
import os
import re
import subprocess
from pathlib import Path

BANNER = "-- Generated by hypr-settings (Displays page). Do not edit by hand: changes are overwritten.\n"
TRANSFORMS = [(0, "Normal"), (1, "Rotated 90° (left side up)"), (2, "Upside down"), (3, "Rotated 270° (right side up)")]
SCALES = [0.75, 1.0, 1.25, 1.5, 1.75, 2.0, 2.5, 3.0]
_MODE = re.compile(r"^(\d+)x(\d+)@([\d.]+)Hz$")


def hyprctl(*args: str, timeout: int = 10) -> subprocess.CompletedProcess:
    return subprocess.run(["hyprctl", *args], capture_output=True, text=True, timeout=timeout)


def read() -> list[dict]:
    """Every screen Hyprland knows about, including ones switched off. [] when Hyprland is not running."""
    try:
        result = hyprctl("monitors", "all", "-j")
        raw = json.loads(result.stdout) if result.returncode == 0 else []
    except (OSError, ValueError, TypeError, subprocess.SubprocessError):
        return []
    out = []
    for m in raw:
        out.append({
            "name": m["name"], "description": (m.get("description") or "").strip(), "width": m["width"], "height": m["height"],
            "refresh": round(float(m["refreshRate"]), 2), "x": m["x"], "y": m["y"], "scale": round(float(m["scale"]), 3),
            "transform": m.get("transform", 0), "vrr": bool(m.get("vrr")), "disabled": bool(m.get("disabled")),
            "modes": list(m.get("availableModes") or []),
        })
    return out


def parse_mode(text: str) -> tuple[int, int, float] | None:
    m = _MODE.match(text.strip())
    return (int(m[1]), int(m[2]), float(m[3])) if m else None


def resolutions(modes: list[str]) -> list[tuple[int, int]]:
    """Distinct resolutions, biggest first."""
    seen = {(w, h) for w, h, _ in filter(None, map(parse_mode, modes))}
    return sorted(seen, key=lambda r: (-r[0] * r[1], -r[0]))


def refresh_rates(modes: list[str], res: tuple[int, int]) -> list[float]:
    rates = {r for w, h, r in filter(None, map(parse_mode, modes)) if (w, h) == res}
    return sorted(rates, reverse=True)


def logical_size(m: dict) -> tuple[int, int]:
    """Size on the shared desktop: pixels divided by scale, width and height swapped when rotated sideways."""
    w, h = m["width"], m["height"]
    if m["transform"] % 2:
        w, h = h, w
    return round(w / m["scale"]), round(h / m["scale"])


def place_beside(m: dict, other: dict, side: str) -> tuple[int, int]:
    """Where to put m so it touches `other` on the given side (left, right, above, below), edges lined up at the top/left."""
    mw, mh = logical_size(m)
    ow, oh = logical_size(other)
    if side == "right":
        return other["x"] + ow, other["y"]
    if side == "left":
        return other["x"] - mw, other["y"]
    if side == "below":
        return other["x"], other["y"] + oh
    return other["x"], other["y"] - mh


def normalize_positions(monitors: list[dict]) -> None:
    """Hyprland copes with negative positions, but shifting everything so the top-left is 0x0 keeps the file tidy."""
    live = [m for m in monitors if not m["disabled"]]
    if not live:
        return
    dx, dy = min(m["x"] for m in live), min(m["y"] for m in live)
    if dx or dy:
        for m in live:
            m["x"] -= dx
            m["y"] -= dy


def overlaps(monitors: list[dict]) -> str | None:
    live = [m for m in monitors if not m["disabled"]]
    for i, a in enumerate(live):
        aw, ah = logical_size(a)
        for b in live[i + 1:]:
            bw, bh = logical_size(b)
            if a["x"] < b["x"] + bw and b["x"] < a["x"] + aw and a["y"] < b["y"] + bh and b["y"] < a["y"] + ah:
                return f"{a['name']} and {b['name']} overlap. Move one of them beside the other."
    return None


def resolve_overlaps(monitors: list[dict], moved: str) -> None:
    """After `moved` grew or turned, push any screen it now covers out to the side it was already on."""
    m = next((x for x in monitors if x["name"] == moved and not x["disabled"]), None)
    if not m:
        return
    mw, mh = logical_size(m)
    for b in monitors:
        if b is m or b["disabled"]:
            continue
        bw, bh = logical_size(b)
        if not (m["x"] < b["x"] + bw and b["x"] < m["x"] + mw and m["y"] < b["y"] + bh and b["y"] < m["y"] + mh):
            continue
        dx = (b["x"] + bw / 2) - (m["x"] + mw / 2)
        dy = (b["y"] + bh / 2) - (m["y"] + mh / 2)
        if abs(dx) / (mw + bw) >= abs(dy) / (mh + bh):
            b["x"] = m["x"] + mw if dx >= 0 else m["x"] - bw
        else:
            b["y"] = m["y"] + mh if dy >= 0 else m["y"] - bh


def mode_text(m: dict) -> str:
    return f"{m['width']}x{m['height']}@{m['refresh']:g}"


def lua_entry(m: dict) -> str:
    name = json.dumps(m["name"])
    if m["disabled"]:
        return f"hl.monitor({{ output = {name}, disabled = true }})"
    parts = [f"output = {name}", f'mode = "{mode_text(m)}"', f'position = "{m["x"]}x{m["y"]}"', f"scale = {m['scale']:g}"]
    if m["transform"]:
        parts.append(f"transform = {m['transform']}")
    if m["vrr"]:
        parts.append("vrr = 1")
    return "hl.monitor({ " + ", ".join(parts) + " })"


def render(monitors: list[dict]) -> str:
    return BANNER + "\n" + "\n".join(lua_entry(m) for m in monitors) + "\n"


def apply(monitors: list[dict]) -> tuple[bool, str]:
    """Makes Hyprland use this layout now. Returns (ok, what went wrong)."""
    for m in monitors:
        try:
            result = hyprctl("eval", lua_entry(m))
        except (OSError, subprocess.SubprocessError) as e:
            return False, f"Could not talk to Hyprland: {e}"
        if result.returncode != 0 or (result.stdout.strip() not in ("", "ok")):
            return False, (result.stdout or result.stderr).strip()[:300] or "Hyprland refused the change."
    return True, ""


def write(path: Path | str, monitors: list[dict]) -> None:
    path = Path(path)
    if path.exists() and path.stat().st_size and BANNER.split(".")[0] not in path.read_text(encoding="utf-8", errors="replace")[:200]:
        path.with_name(path.name + ".bak").write_text(path.read_text(encoding="utf-8", errors="replace"), encoding="utf-8")
    tmp = path.with_name(path.name + f".{os.getpid()}.tmp")
    tmp.write_text(render(monitors), encoding="utf-8")
    os.replace(tmp, path)
