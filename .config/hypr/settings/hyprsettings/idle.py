"""Power & lock page: writes hypridle.local.conf (git-ignored) from the [power] settings and restarts hypridle with it.

autostart.lua starts hypridle with this file when it exists, and with the shipped hypridle.conf otherwise."""

from __future__ import annotations

import os
import shlex
import shutil
import subprocess
from pathlib import Path

BANNER = "# Generated by hypr-settings (Power & lock page). Do not edit by hand: changes are overwritten.\n"
LOCK_SCRIPT = "~/.config/hypr/scripts/lock-screen.sh"
SCREENS_OFF = "hyprctl dispatch 'hl.dsp.dpms({ action = \"off\" })'"


def local_path(hypr_dir: Path | str) -> Path:
    return Path(hypr_dir) / "hypridle.local.conf"



def render(lock_after: int, screen_off_after: int, suspend_after: int, lock_before_sleep: bool, lock_screens: str = "all") -> str:
    """Times are in minutes; 0 leaves that step out. lock_screens: "all", "focused" or a screen name to keep on while
    locked (the others switch off until you unlock)."""
    keep = shlex.quote(lock_screens or "all")
    wake = f"{LOCK_SCRIPT} wake {keep}"
    out = [BANNER, "\ngeneral {\n",
           f"    lock_cmd = {LOCK_SCRIPT} {keep}\n",
           f"    before_sleep_cmd = {'loginctl lock-session' if lock_before_sleep else 'true'}\n",
           # Hold off sleep until the screen is really locked: "auto" only waits when lock_cmd names hyprlock
           f"    inhibit_sleep = {3 if lock_before_sleep else 1}\n",
           f"    after_sleep_cmd = {wake}\n",
           "    ignore_dbus_inhibit = false\n",  # video players and games can still keep the PC awake
           "}\n"]
    steps = []
    if lock_after > 0:
        steps.append((lock_after, "loginctl lock-session", ""))
    if screen_off_after > 0:
        steps.append((screen_off_after, SCREENS_OFF, wake))
    if suspend_after > 0:
        steps.append((suspend_after, "systemctl suspend", ""))
    for minutes, on_timeout, on_resume in steps:
        out.append(f"\nlistener {{\n    timeout = {int(minutes) * 60}\n    on-timeout = {on_timeout}\n")
        if on_resume:
            out.append(f"    on-resume = {on_resume}\n")
        out.append("}\n")
    return "".join(out)


def write(hypr_dir: Path | str, text: str) -> Path:
    path = local_path(hypr_dir)
    tmp = path.with_name(path.name + f".{os.getpid()}.tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)
    return path


def restart(path: Path) -> bool:
    """Restarts a running hypridle with the new file. Nothing to do when it is not running (it picks the file up at
    the next login). True when hypridle was restarted."""
    if not shutil.which("hypridle"):
        return False
    running = subprocess.run(["pgrep", "-x", "hypridle"], capture_output=True).returncode == 0
    if not running:
        return False
    # As a service it reads the file by itself when started (scripts/idle-start.sh)
    if subprocess.run(["systemctl", "--user", "restart", "hypridle.service"], capture_output=True).returncode == 0:
        return True
    subprocess.run(["pkill", "-x", "hypridle"], capture_output=True)
    subprocess.Popen(["hypridle", "-c", str(path)], start_new_session=True,
                     stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, stdin=subprocess.DEVNULL)
    return True
