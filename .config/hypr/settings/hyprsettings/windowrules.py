"""Window rules: what happens to a window when it opens. Built-in rules are in window_rules.lua (tracked, so updates can
add to them); your own, your changes to built-in ones and the ones you switched off are in window_rules_local.lua
(git-ignored). window.lua applies both, and yours win when the names match.

The rules the desktop itself depends on, such as Hearthling's scratchpad, stay in window.lua and are not shown here.
Options the wizard has no control for are kept as they are."""

from __future__ import annotations

import os
import re
import subprocess
from pathlib import Path

from . import overrides
from .overrides import lua_value

BANNER = "-- Generated by hypr-settings (Window rules page). Do not edit by hand: changes are overwritten.\n"
SHAPES = ("normal", "float", "fullscreen", "maximize")
MANAGED = {"name", "match", "workspace", "monitor", "float", "fullscreen", "maximize", "center", "size", "pin", "opacity",
           "idle_inhibit", "no_initial_focus", "border_size", "immediate"}
TOKEN = re.compile(r'\s+|--[^\n]*|"(?:[^"\\]|\\.)*"|[{}=,]|[A-Za-z_]\w*|-?\d+(?:\.\d+)?')
PLAIN_ESCAPE = re.compile(r"\\(.)")


# ---- reading Lua tables --------------------------------------------------------------------------------------------
def parse_table(text: str):
    """The table after `return` in a file of plain data. Raises ValueError on anything else: this reads data, it does
    not run Lua."""
    start = text.find("return")
    if start < 0:
        raise ValueError("no table to read")
    tokens, pos = [], start + len("return")
    while pos < len(text):
        m = TOKEN.match(text, pos)
        if not m:
            raise ValueError(f"cannot read {text[pos:pos + 20]!r}")
        pos = m.end()
        if not m[0].isspace() and not m[0].startswith("--"):
            tokens.append(m[0])
    value, used = _value(tokens, 0)
    if used != len(tokens):
        raise ValueError("more after the table")
    return value


def _value(tokens: list[str], at: int):
    if at >= len(tokens):
        raise ValueError("the table ends early")
    token = tokens[at]
    if token == "{":
        return _table(tokens, at + 1)
    if token.startswith('"'):
        return PLAIN_ESCAPE.sub(lambda m: {"n": "\n", "r": "\r"}.get(m[1], m[1]), token[1:-1]), at + 1
    if token in ("true", "false"):
        return token == "true", at + 1
    if re.fullmatch(r"-?\d+(\.\d+)?", token):
        return (float(token) if "." in token else int(token)), at + 1
    raise ValueError(f"cannot read {token!r}")


def _table(tokens: list[str], at: int):
    keyed, listed = {}, []
    while True:
        if at >= len(tokens):
            raise ValueError("the table ends early")
        if tokens[at] == "}":
            at += 1
            break
        if at + 1 < len(tokens) and tokens[at + 1] == "=":
            key = tokens[at]
            keyed[key], at = _value(tokens, at + 2)
        else:
            item, at = _value(tokens, at)
            listed.append(item)
        if at < len(tokens) and tokens[at] == ",":
            at += 1
    if keyed and listed:
        raise ValueError("a table with both names and a list")
    return keyed or listed, at


def read_shipped(path: Path | str) -> list[dict]:
    return parse_table(Path(path).read_text(encoding="utf-8"))


def read_local(path: Path | str) -> dict:
    """{"off": [names], "rules": [rules]}. Empty when the file is missing or cannot be read."""
    try:
        data = parse_table(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"off": [], "rules": []}
    if not isinstance(data, dict):
        return {"off": [], "rules": []}
    return {"off": list(data.get("off", [])), "rules": list(data.get("rules", []))}


# ---- writing ---------------------------------------------------------------------------------------------------------
def lua_table(value) -> str:
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{k} = {lua_table(v)}" for k, v in value.items()) + " }"
    if isinstance(value, (list, tuple)):
        return "{ " + ", ".join(lua_table(v) for v in value) + " }"
    return lua_value(value)


def render_local(local: dict) -> str:
    rules = "".join(f"        {lua_table(r)},\n" for r in local["rules"])
    return (BANNER + "return {\n    off = " + lua_table(sorted(local["off"])) + ",\n    rules = {\n" + rules + "    },\n}\n")


def write_local(path: Path | str, local: dict) -> None:
    path = Path(path)
    tmp = path.with_name(path.name + f".{os.getpid()}.tmp")
    tmp.write_text(render_local(local), encoding="utf-8")
    os.replace(tmp, path)


def apply() -> tuple[bool, str]:
    """Reloads Hyprland. Rules take effect on windows opened from now on."""
    problem = overrides.config_problem()
    if problem:
        return False, "Not reloaded, so your running desktop is unchanged. This needs fixing first:\n" + problem
    try:
        reloaded = subprocess.run(["hyprctl", "reload"], capture_output=True, text=True, timeout=10)
        if reloaded.returncode != 0:
            return False, (reloaded.stdout or reloaded.stderr).strip()[:300] or "Hyprland did not reload."
        errors = subprocess.run(["hyprctl", "configerrors"], capture_output=True, text=True, timeout=10).stdout.strip()
    except (OSError, subprocess.SubprocessError) as e:
        return False, f"Could not talk to Hyprland: {e}"
    if errors and errors != "[]":
        return False, "Hyprland reported a problem with the config:\n" + errors[:400]
    return True, "Windows you open from now on follow them."


def open_windows() -> list[dict]:
    """What is open now, one line per app and title, for the wizard: {class, title}."""
    import json
    try:
        clients = json.loads(subprocess.run(["hyprctl", "clients", "-j"], capture_output=True, text=True, timeout=5).stdout)
    except (OSError, subprocess.SubprocessError, ValueError):
        return []
    seen, out = set(), []
    for c in clients:
        key = (c.get("class", ""), c.get("title", ""))
        if key[0] and key not in seen and c.get("mapped", True):
            seen.add(key)
            out.append({"class": key[0], "title": key[1]})
    return sorted(out, key=lambda w: (w["class"].lower(), w["title"].lower()))


# ---- the list on the page ----------------------------------------------------------------------------------------------
def entries(shipped: list[dict], local: dict) -> list[dict]:
    """Everything for the page: {rule, kind, on}. kind is builtin, changed (a built-in with your edits) or yours."""
    mine = {r["name"]: r for r in local["rules"] if "name" in r}
    off = set(local["off"])
    out, names = [], set()
    for rule in shipped:
        names.add(rule["name"])
        if rule["name"] in mine:
            out.append({"rule": mine[rule["name"]], "kind": "changed", "on": rule["name"] not in off})
        else:
            out.append({"rule": rule, "kind": "builtin", "on": rule["name"] not in off})
    for rule in local["rules"]:
        if rule.get("name") not in names:
            out.append({"rule": rule, "kind": "yours", "on": rule.get("name") not in off})
    return out


def put_rule(local: dict, rule: dict) -> None:
    """Adds a rule, or replaces the one with its name."""
    for i, old in enumerate(local["rules"]):
        if old.get("name") == rule["name"]:
            local["rules"][i] = rule
            return
    local["rules"].append(rule)


def remove_rule(local: dict, name: str) -> None:
    """Deletes your rule, or puts a built-in one back as it shipped."""
    local["rules"] = [r for r in local["rules"] if r.get("name") != name]
    local["off"] = [n for n in local["off"] if n != name]


def set_on(local: dict, name: str, on: bool) -> None:
    off = [n for n in local["off"] if n != name]
    local["off"] = off if on else off + [name]


def unique_name(wanted: str, taken: set[str]) -> str:
    base = re.sub(r"[^a-z0-9]+", "-", wanted.lower()).strip("-") or "rule"
    name, n = base, 2
    while name in taken:
        name, n = f"{base}-{n}", n + 1
    return name


# ---- patterns and plain words -------------------------------------------------------------------------------------------
KINDS = (("exact", "is exactly"), ("contains", "contains"), ("starts", "starts with"), ("pattern", "matches this pattern"))


def to_pattern(kind: str, text: str) -> str:
    if kind == "pattern":
        return text
    escaped = re.escape(text)
    return {"exact": f"^{escaped}$", "contains": f".*{escaped}.*", "starts": f"^{escaped}.*$"}[kind]


def from_pattern(pattern: str) -> tuple[str, str]:
    """(kind, text) to show for a pattern; what it cannot explain simply is shown as a pattern."""
    special = r"[\\^$.|?*+()\[\]{}]"

    def plain(body):
        # A bare dot is allowed: app ids such as com.foo.bar are nearly always written that way
        text = re.sub(r"\\(.)", r"\1", body)
        return text if not re.search(special, re.sub(r"\\.", "", body).replace(".", "")) else None
    for regex, kind in ((r"\^\((.*)\)\$", "exact"), (r"\^(.*)\.\*\$", "starts"), (r"\^(.*)\$", "exact"), (r"\.\*(.*)\.\*", "contains")):
        m = re.fullmatch(regex, pattern)
        if m and plain(m[1]) is not None:
            return kind, plain(m[1])
    return "pattern", pattern


def app_name(window_class: str) -> str:
    """A readable name from a window class: vesktop -> Vesktop, com.anthropic.Claude -> Claude. The end of an app id can
    be a generic word (com.bitwarden.desktop), and then the part before it is the name."""
    parts = [p for p in window_class.split(".") if p]
    if not parts:
        return window_class
    name = parts[-1]
    if len(parts) > 1 and (len(name) < 4 or name.lower() in ("desktop", "client", "application", "app")):
        name = parts[-2]
    return name[0].upper() + name[1:]


def _either(pattern: str) -> str | None:
    """^(a|b|c)$ -> "A, B or C", when each is a plain name."""
    m = re.fullmatch(r"\^\((.*)\)\$", pattern)
    names = m[1].split("|") if m else []
    if len(names) < 2 or not all(re.fullmatch(r"[\w.-]+", n) for n in names):
        return None
    shown = [app_name(n) for n in names]
    return ", ".join(shown[:-1]) + " or " + shown[-1]


def describe_match(match: dict) -> str:
    words = {"exact": "", "contains": "containing ", "starts": "starting with ", "pattern": "matching "}
    parts = []
    if "class" in match:
        kind, text = from_pattern(str(match["class"]))
        parts.append(_either(str(match["class"])) or (app_name(text) if kind == "exact" else f"Apps {words[kind]}{text}"))
    if "title" in match:
        kind, text = from_pattern(str(match["title"]))
        parts.append((f"titled {words[kind]}{text}" if parts else f"Windows titled {words[kind]}{text}"))
    others = [k for k in match if k not in ("class", "title")]
    if others:
        parts.append("+ " + ", ".join(others))
    return " ".join(parts) or "Every window"


def describe_workspace(value: str) -> str:
    parts = str(value).split()
    silent = "silent" in parts
    target = parts[0] if parts else ""
    place = f"scratch workspace {target[8:]}" if target.startswith("special:") else f"workspace {target}"
    return f"opens on {place}" + (" without switching to it" if silent else "")


def describe_effects(rule: dict) -> list[str]:
    out = []
    if "workspace" in rule:
        out.append(describe_workspace(rule["workspace"]))
    if "monitor" in rule:
        out.append(f"on screen {rule['monitor']}")
    if rule.get("float"):
        words = "floats"
        if isinstance(rule.get("size"), (list, tuple)) and len(rule["size"]) == 2:
            words += f" at {rule['size'][0]} × {rule['size'][1]}"
        out.append(words + (", centred" if rule.get("center") else ""))
    if rule.get("fullscreen"):
        out.append("opens fullscreen")
    if rule.get("maximize"):
        out.append("opens maximised")
    if rule.get("pin"):
        out.append("shows on every workspace")
    if "opacity" in rule:
        try:
            out.append(f"{round(float(str(rule['opacity']).split()[0]) * 100)}% see-through".replace("% see-through", "% opaque"))
        except ValueError:
            out.append("custom opacity")
    if rule.get("idle_inhibit"):
        out.append("keeps the screen awake")
    if rule.get("no_initial_focus"):
        out.append("does not take focus")
    if rule.get("border_size") == 0:
        out.append("no border")
    if rule.get("immediate"):
        out.append("lower lag")
    others = sorted(k for k in rule if k not in MANAGED and k != "enabled")
    if others:
        out.append("also: " + ", ".join(others))
    return out


def summary(rule: dict) -> str:
    text = ", ".join(describe_effects(rule))
    return (text[0].upper() + text[1:]) if text else "Does nothing yet"


# ---- the wizard's choices <-> a rule ---------------------------------------------------------------------------------
def choices_from_rule(rule: dict | None = None) -> dict:
    rule = rule or {}
    match = rule.get("match", {})
    class_kind, class_text = from_pattern(str(match["class"])) if "class" in match else ("exact", "")
    title_kind, title_text = from_pattern(str(match["title"])) if "title" in match else ("exact", "")
    parts = str(rule.get("workspace", "")).split()
    size = rule.get("size")
    sized = isinstance(size, (list, tuple)) and len(size) == 2 and all(isinstance(v, int) for v in size)
    shape = next((s for s in ("float", "fullscreen", "maximize") if rule.get(s)), "normal")
    try:
        opacity = round(float(str(rule["opacity"]).split()[0]) * 100) if "opacity" in rule else 100
    except ValueError:
        opacity = 100
    return {"name": rule.get("name", ""), "class_kind": class_kind, "class": class_text, "title_kind": title_kind,
            "title": title_text, "workspace": parts[0] if parts else "", "silent": "silent" in parts,
            "monitor": str(rule.get("monitor", "")), "shape": shape, "center": bool(rule.get("center")),
            "width": size[0] if sized else 0, "height": size[1] if sized else 0, "pin": bool(rule.get("pin")),
            "opacity": opacity, "awake": bool(rule.get("idle_inhibit")), "no_focus": bool(rule.get("no_initial_focus")),
            "no_border": rule.get("border_size") == 0, "immediate": bool(rule.get("immediate")),
            # Kept as they are: other match conditions, a size given as a formula, options with no control here
            "keep_match": {k: v for k, v in match.items() if k not in ("class", "title")},
            "keep": {k: v for k, v in rule.items() if k not in MANAGED or (k == "size" and not sized)
                     or (k == "border_size" and v != 0)}}


def rule_from_choices(c: dict) -> dict:
    match = dict(c["keep_match"])
    if c["class"].strip():
        match["class"] = to_pattern(c["class_kind"], c["class"].strip())
    if c["title"].strip():
        match["title"] = to_pattern(c["title_kind"], c["title"].strip())
    rule: dict = {"name": c["name"], "match": match}
    if c["workspace"]:
        rule["workspace"] = c["workspace"] + (" silent" if c["silent"] else "")
    if c["monitor"]:
        rule["monitor"] = c["monitor"]
    if c["shape"] in ("float", "fullscreen", "maximize"):
        rule[c["shape"]] = True
    if c["shape"] == "float":
        if c["center"]:
            rule["center"] = True
        if c["width"] and c["height"]:
            rule["size"] = [int(c["width"]), int(c["height"])]
        if c["pin"]:
            rule["pin"] = True
    if c["opacity"] < 100:
        rule["opacity"] = f"{c['opacity'] / 100:g}"
    if c["awake"]:
        rule["idle_inhibit"] = "always"
    if c["no_border"]:
        rule["border_size"] = 0
    for key, field in (("no_focus", "no_initial_focus"), ("immediate", "immediate")):
        if c[key]:
            rule[field] = True
    rule.update(c["keep"])
    return rule


def has_target(c: dict) -> bool:
    return bool(c["class"].strip() or c["title"].strip() or c["keep_match"])


def has_effect(c: dict) -> bool:
    rule = rule_from_choices(c)
    return bool(set(rule) - {"name", "match"})
