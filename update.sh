#!/usr/bin/env bash
set -euo pipefail

# update.sh
# Safely overwrite this repository with the remote branch state.
# Usage: ./update.sh [remote] [branch]
# - Defaults: remote 'origin', branch 'main'.
# Behavior:
# - Fetches the remote first; nothing is touched if that fails.
# - Resets --hard to remote/branch and removes untracked files (git clean -fdx),
#   keeping the machine-local files listed in PRESERVE below.
# - Installs any packages from install/required.txt that are missing.
#   Set SKIP_PACKAGES=1 to skip this step.
# Note: This script no longer creates local backup git branches.
#
# The whole script lives in main(), called on the last line: git reset rewrites
# this file mid-run, and bash would otherwise read the rest of it from the new copy.

# Machine-local files (git-ignored) that must survive the reset and clean, relative to the repo root.
# monitors/workspaces: Hyprland layout. user_settings.local.toml: private settings (calendar links).
# user_overrides.lua: generated by hypr-settings. agent_context.md: your machine context for the assistant.
# .update-branch: saved branch choice. private_modes: your own assistant modes. theme.css / layout.json: the bar's look and arrangement.
PRESERVE=(
  .config/hypr/monitors.conf
  .config/hypr/monitors.lua
  .config/hypr/monitors.lua.bak
  .config/hypr/workspaces.conf
  .config/hypr/workspaces.lua
  .config/hypr/user_settings.local.toml
  .config/hypr/user_overrides.lua
  .config/hypr/assistant/agent_context.md
  .update-branch
  .config/hypr/assistant/private_modes
  .config/waybar/theme.css
  .config/waybar/layout.json
  .config/swaync/theme.css
  .config/hypr/theme.lua
  .config/hypr/hypridle.local.conf
  .config/hypr/hyprlock.local.conf
  .config/rofi/.current_wallpaper
  .config/waybar/colors/colors.css
  .config/rofi/colors.rasi
  .config/swaync/wallust/colors-wallust.css
  .config/hypr/wallust/colors.lua
)

# Older versions of this script moved the local files to ~/.config/backup before fetching,
# and left them there if the fetch failed. Put any stranded ones back.
recover_stranded_backup() {
  local backup="$HOME/.config/backup" name dest
  [[ -d "$backup" ]] || return 0
  for name in monitors.lua workspaces.lua user_settings.local.toml user_overrides.lua agent_context.md; do
    [[ -f "$backup/$name" ]] || continue
    dest="$HOME/.config/hypr/$name"
    [[ "$name" == "agent_context.md" ]] && dest="$HOME/.config/hypr/assistant/$name"
    if [[ -e "$dest" ]]; then
      echo "Note: $backup/$name was left by an earlier update; $dest already exists, so it was not restored."
    else
      echo "Restoring $dest from an earlier interrupted update"
      mv "$backup/$name" "$dest"
    fi
  done
  rmdir "$backup" 2>/dev/null || true
}

# Install packages from install/required.txt that are not installed yet (new ones added by the update).
install_new_packages() {
  [[ "${SKIP_PACKAGES:-0}" == "1" ]] && return 0
  local list="$repo_root/install/required.txt" line pkgs=() missing=()
  [[ -f "$list" ]] || return 0
  command -v pacman >/dev/null 2>&1 || return 0

  while IFS= read -r line || [[ -n "$line" ]]; do
    line="${line%%#*}"
    line="$(echo "$line" | xargs)"
    [[ -n "$line" ]] && pkgs+=("$line")
  done < "$list"
  [[ ${#pkgs[@]} -eq 0 ]] && return 0

  # pacman -T prints the packages that are not installed (and exits non-zero if there are any)
  mapfile -t missing < <(pacman -T "${pkgs[@]}" || true)
  if [[ ${#missing[@]} -eq 0 ]]; then
    echo "All required packages are installed."
    return 0
  fi

  echo "Installing new required packages: ${missing[*]}"
  if command -v paru >/dev/null 2>&1; then
    paru -S --needed --noconfirm "${missing[@]}" || echo "Warning: could not install ${missing[*]}. Run: paru -S ${missing[*]}" >&2
  else
    sudo pacman -S --needed --noconfirm "${missing[@]}" || echo "Warning: could not install ${missing[*]} (AUR packages need paru)." >&2
  fi
}

main() {
  repo_root="$(cd "$(dirname "$0")" && pwd)"
  cd "$repo_root"

  if ! git rev-parse --git-dir >/dev/null 2>&1; then
    echo "Error: not a git repository: $repo_root" >&2
    exit 1
  fi

  recover_stranded_backup

  remote="${1:-origin}"
  # Branch selection priority: UPDATE_BRANCH env > $repo_root/.update-branch file > arg2 > interactive menu > default main
  branch="${2:-}"
  if [[ -n "${UPDATE_BRANCH:-}" ]]; then
    branch="$UPDATE_BRANCH"
  elif [[ -f "$repo_root/.update-branch" ]]; then
    branch="$(<"$repo_root/.update-branch")"
  fi
  # If not provided, offer an interactive menu when running in a terminal
  if [[ -z "$branch" && -t 0 ]]; then
    echo "Select branch to use:"
    echo "  1) main (recommended)"
    echo "  2) dev (unstable)"
    echo "  3) Enter branch name"
    read -rp "Choice [1-3] (default 1): " _choice
    case "$_choice" in
      1) branch="main" ;;
      3) read -rp "Enter branch name: " branch ;;
      *) branch="main" ;;
    esac
  fi
  branch="${branch:-main}"
  timestamp="$(date +%Y%m%d-%H%M%S)"

  echo "Repository: $repo_root"
  echo "Target branch: $branch"
  echo "Remote: $remote"

  # Fetch and check the branch before touching anything, so a network failure leaves everything as it was
  echo "Fetching from $remote..."
  if ! git fetch --prune "$remote"; then
    echo "Error: could not fetch from $remote. Nothing was changed." >&2
    exit 2
  fi
  if ! git show-ref --verify --quiet "refs/remotes/$remote/$branch"; then
    echo "Error: remote branch '$remote/$branch' not found. Nothing was changed." >&2
    exit 2
  fi

  # Older versions tracked some of the PRESERVE files (the wallpaper colours); the reset would delete those,
  # so keep a copy and put back any the reset removed
  local saved f
  saved="$(mktemp -d)"
  for f in "${PRESERVE[@]}"; do
    [[ -f "$f" || -L "$f" ]] && mkdir -p "$saved/$(dirname "$f")" && cp -P "$f" "$saved/$f"
  done

  echo "Resetting local $branch to $remote/$branch (this will discard local commits not on remote)"
  git reset --hard "$remote/$branch"
  for f in "${PRESERVE[@]}"; do
    [[ -e "$f" || -L "$f" || ! ( -e "$saved/$f" || -L "$saved/$f" ) ]] || cp -P "$saved/$f" "$f"
  done
  rm -rf "$saved"

  echo "Removing untracked files, including ignored ones, except machine-local config (git clean -fdx)"
  local keep=() f
  for f in "${PRESERVE[@]}"; do keep+=(-e "/$f"); done
  git clean -fdx "${keep[@]}"

  echo "Updating submodules (if any)"
  git submodule sync --recursive 2>/dev/null || true
  git submodule update --init --recursive 2>/dev/null || true

  echo "Update complete. Local branch '$branch' now matches '$remote/$branch'."

  install_new_packages
  apply_symlinks
  "$HOME/.config/hypr/scripts/first-colours.sh" || true
  # Re-apply the settings Theme page to the files the reset just put back (best-effort)
  PYTHONPATH="$HOME/.config/hypr/settings" python3 -m hyprsettings.design refresh || true
  exit 0
}

# By default, reapply symlinks and some dotfile tasks so the live system matches the repo.
# Set SKIP_SYMLINKS=1 to skip this step.
apply_symlinks() {
  [[ "${SKIP_SYMLINKS:-0}" == "1" ]] && return 0
  echo "Reapplying symlinks and dotfile tasks from repo..."
  REPO_DIR="$repo_root"
  DOTFILES_DIR="$REPO_DIR/.config"

  # Config directories to symlink
  CONFIG_TARGETS=(hypr fastfetch rofi waybar swaync wallust ghostty)
  for dir in "${CONFIG_TARGETS[@]}"; do
    target="$HOME/.config/$dir"
    source="$DOTFILES_DIR/$dir"
    if [[ ! -d "$source" ]]; then
      echo "Source missing: $source (skipping)"
      continue
    fi

    # Special-case 'hypr' to preserve user-local monitor/workspace configs
    if [[ "$dir" == "hypr" ]]; then
      if [[ -L "$target" && "$(readlink "$target")" == "$source" ]]; then
        echo "Already symlinked: $target"
        continue
      fi
      if [[ -e "$target" && ! -d "$target" ]]; then
        echo "Backing up existing $target"
        mv "$target" "$target.bak.$timestamp" || true
      fi
      # Ensure target dir exists
      mkdir -p "$target"
      # Sync files from repo to user config but exclude monitors.lua/workspaces.lua (and legacy .conf variants)
      if command -v rsync >/dev/null 2>&1; then
        rsync -a --exclude='monitors.conf' --exclude='workspaces.conf' --exclude='monitors.lua' --exclude='monitors.lua.bak' --exclude='workspaces.lua' --exclude='user_settings.local.toml' --exclude='agent_context.md' --exclude='user_overrides.lua' "$source/" "$target/"
      else
        # Fallback: use tar to copy excluding those files
        (cd "$source" && tar cf - --exclude='monitors.conf' --exclude='workspaces.conf' --exclude='monitors.lua' --exclude='monitors.lua.bak' --exclude='workspaces.lua' --exclude='user_settings.local.toml' --exclude='agent_context.md' --exclude='user_overrides.lua' .) | (cd "$target" && tar xpf -)
      fi
      echo "Updated $target from $source (excluded: monitors.conf/lua, workspaces.conf/lua). Local copies (if any) were preserved."
      continue
    fi

    if [[ -L "$target" && "$(readlink "$target")" == "$source" ]]; then
      echo "Already symlinked: $target"
      continue
    fi
    [[ -e "$target" ]] && echo "Backing up existing $target" && mv "$target" "$target.bak.$timestamp" || true
    ln -sfn "$source" "$target"
    echo "Symlinked $target -> $source"
  done


  # Starship config
  starship_file="$HOME/.config/starship.toml"
  if [[ -e "$starship_file" ]]; then
    mv "$starship_file" "$starship_file.bak.$timestamp" || true
  fi
  ln -sfn "$DOTFILES_DIR/starship.toml" "$starship_file" || true

  # Wallpapers: add new ones from the repo; never delete or overwrite the user's files
  wallpaper_src="$REPO_DIR/wallpapers"
  wallpaper_dest="$HOME/Pictures/wallpapers"
  if [[ -d "$wallpaper_src" ]]; then
    mkdir -p "$wallpaper_dest"
    cp -r --update=none "$wallpaper_src/." "$wallpaper_dest/"
    echo "Copied new wallpapers to $wallpaper_dest"
  fi

  # Make key scripts executable (best-effort)
  SCRIPT_FILES=(hypr/scripts/ai.sh hypr/scripts/browser.sh hypr/scripts/gamemode.sh hypr/scripts/pywall.sh hypr/scripts/rainbowb.sh hypr/scripts/refresh.sh hypr/scripts/wallust.sh hypr/scripts/first-colours.sh hypr/scripts/exo-terminal.sh hypr/scripts/xfce4-mime-helper rofi/powermenu/powermenu.sh rofi/powermenu/powermenu.py rofi/launchers/launcher.sh rofi/wallpaper/wallpaper.sh)
  for s in "${SCRIPT_FILES[@]}"; do
    sp="$DOTFILES_DIR/$s"
    [[ -f "$sp" ]] && chmod +x "$sp" && echo "Chmod +x $sp"
  done

  # Keep Thunar's "Open Terminal Here" working (stand-in helper in ~/.local/bin, keeps your chosen terminal)
  [[ -x "$DOTFILES_DIR/hypr/scripts/exo-terminal.sh" ]] && "$DOTFILES_DIR/hypr/scripts/exo-terminal.sh" || true

  echo "Symlink and dotfile tasks complete."
}

main "$@"; exit $?
