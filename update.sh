#!/usr/bin/env bash
set -euo pipefail

# update.sh
# Brings this repository up to date and leaves your settings and files alone.
# Usage: ./update.sh [remote] [branch]
# - Defaults: remote 'origin', branch 'main'. Once a 'stable' branch exists new installs follow it; it only moves when install/promote.sh
#   passes on a version that CI has passed. The branch you pick is kept in .update-branch.
# Behavior:
# - Fetches the remote first; nothing is touched if that fails.
# - Stops, changing nothing, if you have commits the remote does not (UPDATE_DISCARD_COMMITS=1 throws them away).
# - Moves to remote/branch. Files git does not track are never deleted: your settings (the files in
#   .gitignore), and anything you added yourself. Edits to tracked files are put back on top. An edit that
#   clashes with the update gives way to it, and is kept in ~/.local/state/hyprdots/update-backups/.
# - Lists what changed, and keeps the list in ~/.local/state/hyprdots/last-update.txt.
# - Installs any packages from install/required.txt that are missing (the desktop itself, not the optional
#   apps: install/apps.sh adds those). Set SKIP_PACKAGES=1 to skip this step.
#
# The whole script lives in main(), called on the last line: git reset rewrites
# this file mid-run, and bash would otherwise read the rest of it from the new copy.

# Machine-local files (git-ignored) that older versions of the repo tracked, or could again, so moving to the new
# version would delete them; they are copied back afterwards. Relative to the repo root.
# monitors/workspaces: Hyprland layout. user_settings.local.toml: private settings (calendar links).
# user_overrides.lua: generated by hypr-settings. agent_context.md: your machine context for the assistant.
# .update-branch: saved branch choice. private_modes: your own assistant modes. theme.css / layout.json: the bar's look and arrangement.
PRESERVE=(
  .config/hypr/monitors.conf
  .config/hypr/monitors.lua
  .config/hypr/monitors.lua.bak
  .config/hypr/workspaces.conf
  .config/hypr/workspaces.lua
  .config/hypr/user_settings.local.toml
  .config/hypr/user_overrides.lua
  .config/hypr/assistant/agent_context.md
  .update-branch
  .config/hypr/assistant/private_modes
  .config/waybar/theme.css
  .config/waybar/layout.json
  .config/swaync/theme.css
  .config/hypr/tray/theme.css
  .config/hypr/window_rules_local.lua
  .config/hypr/theme.lua
  .config/hypr/hypridle.local.conf
  .config/hypr/hyprlock.local.conf
  .config/rofi/.current_wallpaper
  .config/waybar/colors/colors.css
  .config/rofi/colors.rasi
  .config/swaync/wallust/colors-wallust.css
  .config/hypr/wallust/colors.lua
)

# Older versions of this script moved the local files to ~/.config/backup before fetching,
# and left them there if the fetch failed. Put any stranded ones back.
recover_stranded_backup() {
  local backup="$HOME/.config/backup" name dest
  [[ -d "$backup" ]] || return 0
  for name in monitors.lua workspaces.lua user_settings.local.toml user_overrides.lua agent_context.md; do
    [[ -f "$backup/$name" ]] || continue
    dest="$HOME/.config/hypr/$name"
    [[ "$name" == "agent_context.md" ]] && dest="$HOME/.config/hypr/assistant/$name"
    if [[ -e "$dest" ]]; then
      echo "Note: $backup/$name was left by an earlier update; $dest already exists, so it was not restored."
    else
      echo "Restoring $dest from an earlier interrupted update"
      mv "$backup/$name" "$dest"
    fi
  done
  rmdir "$backup" 2>/dev/null || true
}

# Install packages from install/required.txt that are not installed yet (new ones added by the update).
install_new_packages() {
  [[ "${SKIP_PACKAGES:-0}" == "1" ]] && return 0
  local list="$repo_root/install/required.txt" line pkgs=() missing=()
  [[ -f "$list" ]] || return 0
  command -v pacman >/dev/null 2>&1 || return 0

  while IFS= read -r line || [[ -n "$line" ]]; do
    line="${line%%#*}"
    line="$(echo "$line" | xargs)"
    [[ -n "$line" ]] && pkgs+=("$line")
  done < "$list"
  [[ ${#pkgs[@]} -eq 0 ]] && return 0

  # pacman -T prints the packages that are not installed (and exits non-zero if there are any)
  mapfile -t missing < <(pacman -T "${pkgs[@]}" || true)
  if [[ ${#missing[@]} -eq 0 ]]; then
    echo "All required packages are installed."
    return 0
  fi

  echo "Installing new required packages: ${missing[*]}"
  if command -v paru >/dev/null 2>&1; then
    paru -S --needed --noconfirm "${missing[@]}" || echo "Warning: could not install ${missing[*]}. Run: paru -S ${missing[*]}" >&2
  else
    sudo pacman -S --needed --noconfirm "${missing[@]}" || echo "Warning: could not install ${missing[*]} (AUR packages need paru)." >&2
  fi
}

main() {
  repo_root="$(cd "$(dirname "$0")" && pwd)"
  cd "$repo_root"

  if ! git rev-parse --git-dir >/dev/null 2>&1; then
    echo "Error: not a git repository: $repo_root" >&2
    exit 1
  fi

  recover_stranded_backup

  remote="${1:-origin}"
  # Branch selection priority: UPDATE_BRANCH env > $repo_root/.update-branch file > arg2 > interactive menu > default main
  branch="${2:-}"
  if [[ -n "${UPDATE_BRANCH:-}" ]]; then
    branch="$UPDATE_BRANCH"
  elif [[ -f "$repo_root/.update-branch" ]]; then
    branch="$(<"$repo_root/.update-branch")"
  fi
  # If not provided, offer an interactive menu when running in a terminal
  # (only once there is a stable branch to choose: picking it before then would break every later update)
  if [[ -z "$branch" && -t 0 ]] && git ls-remote --exit-code --heads "$remote" stable >/dev/null 2>&1; then
    echo "Which version do you want to follow?"
    echo "  1) stable: tested first (recommended)"
    echo "  2) main: the newest, and may break"
    echo "  3) Enter branch name"
    read -rp "Choice [1-3] (default 1): " _choice
    case "$_choice" in
      2) branch="main" ;;
      3) read -rp "Enter branch name: " branch ;;
      *) branch="stable" ;;
    esac
    [[ -n "$branch" ]] && printf '%s\n' "$branch" > "$repo_root/.update-branch"
  fi
  branch="${branch:-main}"
  timestamp="$(date +%Y%m%d-%H%M%S)"
  backups="${XDG_STATE_HOME:-$HOME/.local/state}/hyprdots/update-backups/$timestamp"

  echo "Repository: $repo_root"
  echo "Target branch: $branch"
  echo "Remote: $remote"

  # Fetch and check the branch before touching anything, so a network failure leaves everything as it was
  echo "Fetching from $remote..."
  if ! git fetch --prune "$remote"; then
    echo "Error: could not fetch from $remote. Nothing was changed." >&2
    exit 2
  fi
  if ! git show-ref --verify --quiet "refs/remotes/$remote/$branch"; then
    echo "Error: remote branch '$remote/$branch' not found. Nothing was changed." >&2
    exit 2
  fi

  # Commits only this PC has would be lost for good, so do not guess
  # (commits on any branch of the remote are safe, which lets you move from main to the older stable)
  local target="$remote/$branch" ahead=0 own
  ahead="$(git rev-list --count HEAD --not --remotes="$remote")"
  if git show-ref --verify --quiet "refs/heads/$branch"; then
    own="$(git rev-list --count "refs/heads/$branch" --not --remotes="$remote")"
    (( own > ahead )) && ahead="$own"
  fi
  if (( ahead > 0 )) && [[ "${UPDATE_DISCARD_COMMITS:-0}" != "1" ]]; then
    echo "Error: you have $ahead commit(s) that $target does not. Nothing was changed." >&2
    echo "Push them first, or run UPDATE_DISCARD_COMMITS=1 $0 to throw them away." >&2
    exit 3
  fi

  # Older versions tracked some of the PRESERVE files (the wallpaper colours); moving would delete those,
  # so keep a copy and put back any it removed
  local saved f
  saved="$(mktemp -d)"
  for f in "${PRESERVE[@]}"; do
    [[ -f "$f" || -L "$f" ]] && mkdir -p "$saved/$(dirname "$f")" && cp -P "$f" "$saved/$f"
  done

  # Your edits to tracked files, one patch per file, so that one clash costs only that file. A copy of each stays in the backup.
  local edited=() patches clashed=()
  patches="$(mktemp -d)"
  mapfile -t edited < <(git diff --name-only HEAD)
  for f in "${edited[@]}"; do
    mkdir -p "$patches/$(dirname "$f")"
    git diff --binary HEAD -- "$f" > "$patches/$f.patch"
    if [[ -f "$f" ]]; then
      mkdir -p "$backups/$(dirname "$f")"
      cp -P "$f" "$backups/$f"
    fi
  done
  # A file of yours with the name of one the update adds: the update's goes in, yours is kept in the backup
  while IFS= read -r f; do
    if [[ -e "$f" ]] && ! git ls-files --error-unmatch "$f" >/dev/null 2>&1; then
      mkdir -p "$backups/$(dirname "$f")"
      cp -P "$f" "$backups/$f"
      clashed+=("$f")
    fi
  done < <(git diff --name-only --diff-filter=A HEAD "$target")

  local before
  before="$(git rev-parse HEAD)"
  echo "Moving to $target"
  git checkout -f -B "$branch" "$target"
  for f in "${PRESERVE[@]}"; do
    [[ -e "$f" || -L "$f" || ! ( -e "$saved/$f" || -L "$saved/$f" ) ]] || cp -P "$saved/$f" "$f"
  done
  rm -rf "$saved"

  for f in "${edited[@]}"; do
    if git apply "$patches/$f.patch" 2>/dev/null; then
      echo "Kept your edit to $f"
    else
      clashed+=("$f")
    fi
  done
  rm -rf "$patches"
  if (( ${#clashed[@]} > 0 )); then
    echo "These clash with the update, so the update's version is in place. Yours are saved in $backups:" >&2
    printf '  %s\n' "${clashed[@]}" >&2
    command -v notify-send >/dev/null 2>&1 && notify-send -u critical "Update" "${#clashed[@]} of your edited files clashed with the update. Copies are in $backups" || true
  fi

  # Old compiled Python is the only thing worth clearing: nothing else untracked is this script's to delete
  find .config -type d -name __pycache__ -prune -exec rm -rf {} + 2>/dev/null || true

  echo "Updating submodules (if any)"
  git submodule sync --recursive 2>/dev/null || true
  git submodule update --init --recursive 2>/dev/null || true

  echo "Update complete. Local branch '$branch' now matches '$remote/$branch'."

  install_new_packages
  apply_symlinks
  install_missing_gpu_drivers
  "$HOME/.config/hypr/scripts/first-colours.sh" || true
  # Re-apply the settings Theme page to the files the reset just put back (best-effort)
  PYTHONPATH="$HOME/.config/hypr/settings" python3 -m hyprsettings.design refresh || true
  show_changes "$before"
  exit 0
}

# A graphics card without its drivers: offered in a terminal, otherwise only mentioned
install_missing_gpu_drivers() {
  [[ "${SKIP_PACKAGES:-0}" == "1" ]] && return 0
  local vendor answer pkgs=()
  while IFS= read -r vendor; do
    [[ -n "$vendor" ]] && mapfile -t -O "${#pkgs[@]}" pkgs < <(sed 's/#.*//; /^[[:space:]]*$/d' "$repo_root/install/gpu-$vendor.txt")
  done < <("$repo_root/.config/hypr/scripts/gpu-check.sh")
  (( ${#pkgs[@]} > 0 )) || return 0
  echo "This PC's graphics drivers are not installed: ${pkgs[*]}"
  [[ -t 0 ]] || return 0
  read -rp "Install them now? [Y/n] " answer || return 0
  [[ "$answer" == [nN]* ]] || sudo pacman -S --needed --noconfirm "${pkgs[@]}" || echo "Could not install them. See the error above." >&2
}

# What this update brought, in the words of its commits. Moving back to an older version lists nothing.
show_changes() {
  local list="${XDG_STATE_HOME:-$HOME/.local/state}/hyprdots/last-update.txt" count
  count="$(git rev-list --no-merges --count "$1..HEAD")"
  if (( count == 0 )); then
    echo "Nothing new in this update."
    return 0
  fi
  mkdir -p "$(dirname "$list")"
  git log --no-merges --format='- %s' "$1..HEAD" > "$list"
  echo
  echo "What's new ($count):"
  head -n 20 "$list"
  (( count > 20 )) && echo "...and $(( count - 20 )) more, in $list"
  command -v notify-send >/dev/null 2>&1 && notify-send "Update finished" "$count new. $(head -n 3 "$list")" || true
}

# By default, reapply symlinks and some dotfile tasks so the live system matches the repo.
# Set SKIP_SYMLINKS=1 to skip this step.
apply_symlinks() {
  [[ "${SKIP_SYMLINKS:-0}" == "1" ]] && return 0
  echo "Reapplying symlinks and dotfile tasks from repo..."
  REPO_DIR="$repo_root"
  DOTFILES_DIR="$REPO_DIR/.config"

  # Config directories to symlink
  CONFIG_TARGETS=(hypr fastfetch rofi waybar swaync wallust ghostty)
  for dir in "${CONFIG_TARGETS[@]}"; do
    target="$HOME/.config/$dir"
    source="$DOTFILES_DIR/$dir"
    if [[ ! -d "$source" ]]; then
      echo "Source missing: $source (skipping)"
      continue
    fi

    # Special-case 'hypr' to preserve user-local monitor/workspace configs
    if [[ "$dir" == "hypr" ]]; then
      if [[ -L "$target" && "$(readlink "$target")" == "$source" ]]; then
        echo "Already symlinked: $target"
        continue
      fi
      if [[ -e "$target" && ! -d "$target" ]]; then
        echo "Backing up existing $target"
        mv "$target" "$target.bak.$timestamp" || true
      fi
      # Ensure target dir exists
      mkdir -p "$target"
      # Sync files from repo to user config but exclude monitors.lua/workspaces.lua (and legacy .conf variants)
      if command -v rsync >/dev/null 2>&1; then
        rsync -a --exclude='monitors.conf' --exclude='workspaces.conf' --exclude='monitors.lua' --exclude='monitors.lua.bak' --exclude='workspaces.lua' --exclude='user_settings.local.toml' --exclude='agent_context.md' --exclude='user_overrides.lua' "$source/" "$target/"
      else
        # Fallback: use tar to copy excluding those files
        (cd "$source" && tar cf - --exclude='monitors.conf' --exclude='workspaces.conf' --exclude='monitors.lua' --exclude='monitors.lua.bak' --exclude='workspaces.lua' --exclude='user_settings.local.toml' --exclude='agent_context.md' --exclude='user_overrides.lua' .) | (cd "$target" && tar xpf -)
      fi
      echo "Updated $target from $source (excluded: monitors.conf/lua, workspaces.conf/lua). Local copies (if any) were preserved."
      continue
    fi

    if [[ -L "$target" && "$(readlink "$target")" == "$source" ]]; then
      echo "Already symlinked: $target"
      continue
    fi
    # A folder of your own stays: replacing it belongs to a fresh install, not an update
    if [[ -e "$target" && ! -L "$target" ]]; then
      echo "Keeping your own $target"
      continue
    fi
    ln -sfn "$source" "$target"
    echo "Symlinked $target -> $source"
  done


  # Starship config
  starship_file="$HOME/.config/starship.toml"
  if [[ -e "$starship_file" && ! -L "$starship_file" ]]; then
    echo "Keeping your own $starship_file"
  else
    ln -sfn "$DOTFILES_DIR/starship.toml" "$starship_file" || true
  fi

  # Wallpapers: add new ones from the repo; never delete or overwrite the user's files
  wallpaper_src="$REPO_DIR/wallpapers"
  wallpaper_dest="$HOME/Pictures/wallpapers"
  if [[ -d "$wallpaper_src" ]]; then
    mkdir -p "$wallpaper_dest"
    cp -r --update=none "$wallpaper_src/." "$wallpaper_dest/"
    echo "Copied new wallpapers to $wallpaper_dest"
  fi

  # Make key scripts executable (best-effort)
  # Every tracked script with a #! line (a hand-kept list here fell behind the installer's)
  local f
  while read -r f; do
    [[ -f "$REPO_DIR/$f" ]] && head -c2 "$REPO_DIR/$f" | grep -q '#!' && chmod +x "$REPO_DIR/$f"
  done < <(git -C "$REPO_DIR" ls-files .config bash install)

  # Only a new install should see the first-run welcome
  mkdir -p "$HOME/.local/state/hyprdots" && touch "$HOME/.local/state/hyprdots/welcomed"

  # What runs in the background picks up the update now, rather than at the next login
  if [[ -n "${HYPRLAND_INSTANCE_SIGNATURE:-}" ]]; then
    "$HOME/.config/hypr/scripts/desktop-services.sh" start || true
    # Safe mode keeps the desktop usable if a file fails to load, but you should still hear about it
    if command -v Hyprland >/dev/null && ! Hyprland --verify-config -c "$HOME/.config/hypr/hyprland.lua" >/dev/null 2>&1; then
      echo "Warning: the Hyprland config has a problem after this update. Run: hyprctl configerrors"
    fi
  fi

  # Keep Thunar's "Open Terminal Here" working (stand-in helper in ~/.local/bin, keeps your chosen terminal)
  [[ -x "$DOTFILES_DIR/hypr/scripts/exo-terminal.sh" ]] && "$DOTFILES_DIR/hypr/scripts/exo-terminal.sh" || true

  echo "Symlink and dotfile tasks complete."
}

main "$@"; exit $?
