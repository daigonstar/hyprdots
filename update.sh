#!/usr/bin/env bash
set -euo pipefail

# update.sh
# Safely overwrite this repository with the remote branch state.
# Usage: ./update.sh [remote] [branch]
# - Defaults: remote 'origin', branch 'dev'.
# Behavior:
# - Fetches the remote and resets --hard to remote/branch.
# - Removes untracked files (git clean -fdx).
# Note: This script no longer creates local backup git branches.

# Backup Hyprland monitor and workspace configs (machine-local, gitignored, Lua since the 0.55+ migration)
  echo "Moving Hyprland monitor and workspace configs to backup folder..."
  mkdir -p "$HOME/.config/backup"
  [[ -f "$HOME/.config/hypr/monitors.lua" ]] && mv "$HOME/.config/hypr/monitors.lua" "$HOME/.config/backup/monitors.lua"
  [[ -f "$HOME/.config/hypr/workspaces.lua" ]] && mv "$HOME/.config/hypr/workspaces.lua" "$HOME/.config/backup/workspaces.lua"
  # Private settings (calendar links) are git-ignored, so git clean -fdx below would delete them
  [[ -f "$HOME/.config/hypr/user_settings.local.toml" ]] && mv "$HOME/.config/hypr/user_settings.local.toml" "$HOME/.config/backup/user_settings.local.toml"
  # Your machine context for the assistant is git-ignored too (the tracked file is agent_context.example.md)
  # Generated by hypr-settings (Hyprland look, default apps, startup apps): git-ignored as well
  [[ -f "$HOME/.config/hypr/user_overrides.lua" ]] && mv "$HOME/.config/hypr/user_overrides.lua" "$HOME/.config/backup/user_overrides.lua"
  [[ -f "$HOME/.config/hypr/assistant/agent_context.md" ]] && mv "$HOME/.config/hypr/assistant/agent_context.md" "$HOME/.config/backup/agent_context.md"

repo_root="$(cd "$(dirname "$0")" && pwd)"
cd "$repo_root"

if ! git rev-parse --git-dir >/dev/null 2>&1; then
  echo "Error: not a git repository: $repo_root" >&2
  exit 1
fi

remote="${1:-origin}"
# Branch selection priority: UPDATE_BRANCH env > $repo_root/.update-branch file > arg2 > interactive menu > default dev
branch="${2:-}"
if [[ -n "${UPDATE_BRANCH:-}" ]]; then
  branch="$UPDATE_BRANCH"
elif [[ -f "$repo_root/.update-branch" ]]; then
  branch="$(<"$repo_root/.update-branch")"
fi
# If not provided, offer an interactive menu when running in a terminal
if [[ -z "$branch" && -t 0 ]]; then
  echo "Select branch to use:"
  echo "  1) main (end users)"
  echo "  2) dev (unstable)"
  echo "  3) Enter branch name"
  read -rp "Choice [1-3] (default 2): " _choice
  case "$_choice" in
    1) branch="main" ;;
    3) read -rp "Enter branch name: " branch ;;
    *) branch="dev" ;;
  esac
fi
branch="${branch:-dev}"
timestamp="$(date +%Y%m%d-%H%M%S)"

echo "Repository: $repo_root"
echo "Target branch: $branch"
echo "Remote: $remote"

echo "Fetching from $remote..."
git fetch --prune "$remote"

if git show-ref --verify --quiet "refs/remotes/$remote/$branch"; then
  echo "Resetting local $branch to $remote/$branch (this will discard local commits not on remote)"
  git reset --hard "$remote/$branch"

  echo "Removing untracked files, including ignored ones (git clean -fdx)"
  git clean -fdx

  echo "Updating submodules (if any)"
  git submodule sync --recursive 2>/dev/null || true
  git submodule update --init --recursive 2>/dev/null || true

  echo "Update complete. Local branch '$branch' now matches '$remote/$branch'."
else
  echo "Error: remote branch '$remote/$branch' not found. Aborting." >&2
  exit 2
fi
  # By default, reapply symlinks and some dotfile tasks so the live system matches the repo.
  # Set SKIP_SYMLINKS=1 to skip this step.
  apply_symlinks() {
    [[ "${SKIP_SYMLINKS:-0}" == "1" ]] && return 0
    echo "Reapplying symlinks and dotfile tasks from repo..."
    REPO_DIR="$repo_root"
    DOTFILES_DIR="$REPO_DIR/.config"

    # Config directories to symlink
    CONFIG_TARGETS=(hypr fastfetch rofi waybar swaync wallust ghostty)
    for dir in "${CONFIG_TARGETS[@]}"; do
      target="$HOME/.config/$dir"
      source="$DOTFILES_DIR/$dir"
      if [[ ! -d "$source" ]]; then
        echo "Source missing: $source (skipping)"
        continue
      fi

      # Special-case 'hypr' to preserve user-local monitor/workspace configs
      if [[ "$dir" == "hypr" ]]; then
        if [[ -L "$target" && "$(readlink "$target")" == "$source" ]]; then
          echo "Already symlinked: $target"
          continue
        fi
        if [[ -e "$target" && ! -d "$target" ]]; then
          echo "Backing up existing $target"
          mv "$target" "$target.bak.$timestamp" || true
        fi
        # Ensure target dir exists
        mkdir -p "$target"
        # Sync files from repo to user config but exclude monitors.lua/workspaces.lua (and legacy .conf variants)
        if command -v rsync >/dev/null 2>&1; then
          rsync -a --delete --exclude='monitors.conf' --exclude='workspaces.conf' --exclude='monitors.lua' --exclude='monitors.lua.bak' --exclude='workspaces.lua' --exclude='user_settings.local.toml' --exclude='agent_context.md' --exclude='user_overrides.lua' "$source/" "$target/"
        else
          # Fallback: use tar to copy excluding those files
          (cd "$source" && tar cf - --exclude='monitors.conf' --exclude='workspaces.conf' --exclude='monitors.lua' --exclude='monitors.lua.bak' --exclude='workspaces.lua' --exclude='user_settings.local.toml' --exclude='agent_context.md' --exclude='user_overrides.lua' .) | (cd "$target" && tar xpf -)
        fi
        echo "Updated $target from $source (excluded: monitors.conf/lua, workspaces.conf/lua). Local copies (if any) were preserved."
        continue
      fi

      if [[ -L "$target" && "$(readlink "$target")" == "$source" ]]; then
        echo "Already symlinked: $target"
        continue
      fi
      [[ -e "$target" ]] && echo "Backing up existing $target" && mv "$target" "$target.bak.$timestamp" || true
      ln -sfn "$source" "$target"
      echo "Symlinked $target -> $source"
    done


    # Starship config
    starship_file="$HOME/.config/starship.toml"
    if [[ -e "$starship_file" ]]; then
      mv "$starship_file" "$starship_file.bak.$timestamp" || true
    fi
    ln -sfn "$DOTFILES_DIR/starship.toml" "$starship_file" || true

    # Wallpapers: copy if present in repo
    wallpaper_src="$REPO_DIR/wallpapers"
    wallpaper_dest="$HOME/Pictures/wallpapers"
    if [[ -d "$wallpaper_src" ]]; then
      [[ -e "$wallpaper_dest" ]] && rm -rf "$wallpaper_dest"
      cp -r "$wallpaper_src" "$wallpaper_dest"
      echo "Copied wallpapers to $wallpaper_dest"
    fi

    # Make key scripts executable (best-effort)
    SCRIPT_FILES=(hypr/scripts/ai.sh hypr/scripts/browser.sh hypr/scripts/gamemode.sh hypr/scripts/pywall.sh hypr/scripts/rainbowb.sh hypr/scripts/refresh.sh hypr/scripts/wallust.sh hypr/scripts/exo-terminal.sh hypr/scripts/xfce4-mime-helper rofi/powermenu/powermenu.sh rofi/powermenu/powermenu.py rofi/launchers/launcher.sh rofi/wallpaper/wallpaper.sh)
    for s in "${SCRIPT_FILES[@]}"; do
      sp="$DOTFILES_DIR/$s"
      [[ -f "$sp" ]] && chmod +x "$sp" && echo "Chmod +x $sp"
    done

    # Keep Thunar's "Open Terminal Here" working (stand-in helper in ~/.local/bin, keeps your chosen terminal)
    [[ -x "$DOTFILES_DIR/hypr/scripts/exo-terminal.sh" ]] && "$DOTFILES_DIR/hypr/scripts/exo-terminal.sh" || true

    echo "Symlink and dotfile tasks complete."
  }

  apply_symlinks
# Move backups to live
  echo "Restoring Hyprland monitor and workspace configs from backup folder..."
  [[ -f "$HOME/.config/backup/monitors.lua" ]] && mv "$HOME/.config/backup/monitors.lua" "$HOME/.config/hypr/monitors.lua"
  [[ -f "$HOME/.config/backup/workspaces.lua" ]] && mv "$HOME/.config/backup/workspaces.lua" "$HOME/.config/hypr/workspaces.lua"
  [[ -f "$HOME/.config/backup/user_settings.local.toml" ]] && mv "$HOME/.config/backup/user_settings.local.toml" "$HOME/.config/hypr/user_settings.local.toml"
  [[ -f "$HOME/.config/backup/user_overrides.lua" ]] && mv "$HOME/.config/backup/user_overrides.lua" "$HOME/.config/hypr/user_overrides.lua"
  [[ -f "$HOME/.config/backup/agent_context.md" ]] && mv "$HOME/.config/backup/agent_context.md" "$HOME/.config/hypr/assistant/agent_context.md"
  rmdir "$HOME/.config/backup" 2>/dev/null || true
  
  exit 0
